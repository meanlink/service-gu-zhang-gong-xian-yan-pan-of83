import hashlib, json
def checksum(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, ensure_ascii=False, allow_nan=False).encode()).hexdigest()
def dataset_dict(d):
    return {'id':d.id, 'name':d.name, 'source':d.source, 'rows':len(d.records), 'checksum':d.checksum, 'visibility':d.visibility, 'scope_confirmed':d.scope_confirmed, 'created_at':d.created_at}
def job_dict(j):
    return {k:getattr(j,k) for k in ['id','name','dataset_id','params','status','result','error','cancel_reason','approved','created_by','created_at','finished_at']}
def report_dict(r):
    return {k:getattr(r,k) for k in ['id','name','job_id','destination','interval_seconds','next_run','enabled']}
def delivery_dict(d):
    return {k:getattr(d,k) for k in ['id','report_id','created_at','checksum','filename','destination']}
def grant_dict(g, user=None):
    data={k:getattr(g,k) for k in ['id','dataset_id','user_id','granted_by','created_at']}
    if user is not None:
        data['user']={'email':user.email,'name':user.name,'role':user.role}
    return data
